    public function findByLocale(string $locale): array
    {
        return $this->createQueryBuilder('n')
            ->andWhere('n.locale = :locale')
            ->setParameter('locale', $locale)
            ->orderBy('n.position', 'DESC')
            ->getQuery()
            ->getResult()
